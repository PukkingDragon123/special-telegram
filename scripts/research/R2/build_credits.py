"""Build references/credits/R2-food.md from the label / food / props manifests and verify file coverage.
Usage: python3 -I build_credits.py"""
import json
import os
from urllib.parse import urlparse

ROOT = "/home/user/special-telegram"
DIRS = {"img/labels": "labels", "textures/food": "textures", "textures/props": "textures"}
WEB_LIC = "unknown — real web photo, used per client instruction 2026-10-19 (clear or replace before public release)"


def pub(url):
    try:
        return urlparse(url).netloc.replace("www.", "") or "unknown"
    except Exception:  # noqa: BLE001
        return "unknown"


def main():
    rows, problems = [], []
    for d, key in DIRS.items():
        base = os.path.join(ROOT, "public/assets", d)
        man = json.load(open(os.path.join(base, "manifest.json"), encoding="utf-8"))
        listed = set()
        for e in man[key]:
            files = e["files"]
            for f in files:
                listed.add(f)
                if not os.path.exists(os.path.join(base, f)):
                    problems.append(f"missing on disk: {d}/{f}")
            if key == "labels":
                srcs = [{"image_url": e.get("source_image_url", ""), "page_url": e.get("source_page_url", "")}]
            else:
                srcs = e["sources"]
            for f in files:
                for s in srcs:
                    if "asset" in s:
                        rows.append((f"public/assets/{d}/{f}", s["url"], "ambientCG (Lennart Demes)", "CC0 1.0"))
                    else:
                        url = s.get("image_url") or s.get("page_url") or ""
                        page = s.get("page_url") or ""
                        author = f"unknown (published on {pub(page or url)})"
                        src = url + (f" (page: {page})" if page and page != url else "")
                        rows.append((f"public/assets/{d}/{f}", src, author, WEB_LIC))
        on_disk = {f for f in os.listdir(base) if f != "manifest.json"}
        for f in sorted(on_disk - listed):
            problems.append(f"not in manifest: {d}/{f}")
    out = os.path.join(ROOT, "references/credits/R2-food.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("# Credits — R2-food (labels, food textures, prop textures)\n\n")
        fh.write("Generated by `scripts/research/R2/build_credits.py` from the three `manifest.json` files.\n\n")
        fh.write("> **Licence warning.** On 2026-10-19 the client asked for real Thai product packaging and real food "
                 "photos from the internet (\"any licence\"). Those files are marked *unknown*: they carry real "
                 "trademarks and have not been cleared. They are fine for the private prototype, but before any "
                 "public release they need permission or replacement (the parody label set and its generator are kept "
                 "in `references/food/_raw/labels_parody_superseded/` and `scripts/research/R2/make_labels.py`). "
                 "ambientCG assets are CC0.\n\n")
        fh.write("| Shipped path | Source URL | Author | Licence |\n|---|---|---|---|\n")
        for r in rows:
            fh.write("| " + " | ".join(x.replace("|", "\\|") for x in r) + " |\n")
        fh.write("\nReference photos in `references/food/web/` are for looking only (git-ignored, not shipped); "
                 "their sources are in `references/food/web/_sources.csv`.\n")
    print("rows", len(rows))
    print("\n".join(problems) or "coverage OK")


if __name__ == "__main__":
    main()
