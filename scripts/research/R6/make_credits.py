#!/usr/bin/env python3
"""R6-pbr: write references/credits/R6-pbr.md from the PBR / foliage / HDRI manifests, resolving
every source URL to its real author + licence. Also replaces 'see credits' author placeholders in
the manifests with the resolved names.
Usage: python3 -I make_credits.py
"""
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import r6lib as L  # noqa: E402

ROOT = L.ROOT
PBR = os.path.join(ROOT, "public/assets/textures/pbr")
FOL = os.path.join(ROOT, "public/assets/textures/foliage")
HDR = os.path.join(ROOT, "public/assets/hdri")
OUT = os.path.join(ROOT, "references/credits/R6-pbr.md")

LIC_URL = {
    "CC0": "https://creativecommons.org/publicdomain/zero/1.0/",
    "CC BY 2.0": "https://creativecommons.org/licenses/by/2.0/",
    "CC BY-SA 2.0": "https://creativecommons.org/licenses/by-sa/2.0/",
    "CC BY 3.0 us": "https://creativecommons.org/licenses/by/3.0/us/",
    "CC BY-SA 4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
    "Public Domain Mark": "https://creativecommons.org/publicdomain/mark/1.0/",
}


def load_sources():
    ph = json.load(open(os.path.join(L.CACHE, "catalog/ph_textures.json")))
    ph.update(json.load(open(os.path.join(L.CACHE, "catalog/ph_models.json"))))
    ph.update(json.load(open(os.path.join(L.CACHE, "catalog/ph_hdris.json"))))
    photos = {}
    for f in glob.glob(os.path.join(L.CACHE, "commons/*_selected.json")):
        for r in json.load(open(f)).values():
            artist = re.sub(r"\s*\([-0-9.,\s]+\)", "", r.get("artist") or "unknown").strip()
            photos[r["descurl"]] = dict(author=artist, license=r["license"].strip(), title=r["title"].replace("File:", ""))
    for f in glob.glob(os.path.join(L.CACHE, "openverse/*_selected.json")):
        for r in json.load(open(f)).values():
            lic = {"by": "CC BY", "by-sa": "CC BY-SA", "pdm": "Public Domain Mark", "cc0": "CC0"}.get(r["license"], r["license"])
            if r["license"] in ("by", "by-sa"):
                lic += " " + str(r.get("license_version") or "")
            photos[r["landing"]] = dict(author=r.get("creator") or "unknown", license=lic.strip(),
                                        title=r.get("title") or "", via="Flickr via Openverse")
    return ph, photos


def resolve(url, ph, photos):
    url = url.strip()
    m = re.match(r"https://polyhaven\.com/a/([\w\-]+)", url)
    if m:
        c = ph.get(m.group(1), {})
        return dict(url=url, author=", ".join((c.get("authors") or {}).keys()) or "Poly Haven", license="CC0",
                    what=f"Poly Haven '{c.get('name', m.group(1))}'")
    m = re.match(r"https://ambientcg\.com/a/([\w\-]+)", url)
    if m:
        return dict(url=url, author="Lennart Demes (ambientCG)", license="CC0", what=f"ambientCG {m.group(1)}")
    if url in photos:
        p = photos[url]
        return dict(url=url, author=p["author"], license=p["license"], what=f"photo '{p['title']}'" + (f" ({p['via']})" if p.get("via") else " (Wikimedia Commons)"))
    return None


def main():
    ph, photos = load_sources()
    rows = []
    unresolved = []
    for name, base, man_path in (("PBR", PBR, os.path.join(PBR, "manifest.json")), ("Foliage", FOL, os.path.join(FOL, "manifest.json")),
                                 ("HDRI", HDR, os.path.join(HDR, "manifest.json"))):
        man = json.load(open(man_path))
        changed = False
        for key, e in man.items():
            if key.startswith("_"):
                continue
            urls = [u for u in (e.get("sourceUrl") or "").split(";") if u.strip()]
            res = []
            for u in urls:
                r = resolve(u, ph, photos)
                if r is None:
                    unresolved.append((key, u))
                else:
                    res.append(r)
            if name == "HDRI":
                files = [e["file1k"], e["file2k"], e["preview"]]
            else:
                files = sorted(os.path.relpath(p, base) for p in glob.glob(os.path.join(base, key, "*")))
            shipped = f"public/assets/{os.path.relpath(base, os.path.join(ROOT, 'public/assets'))}/{key}/ ({', '.join(os.path.basename(f) for f in files)})" \
                if name != "HDRI" else "public/assets/hdri/" + ", ".join(files)
            if not res:
                res = [dict(url="(generated by R6 from the listed sources)", author="R6-pbr", license=e.get("license", ""), what=e.get("source", ""))]
            for r in res:
                rows.append((name, key, shipped, r))
            authors = "; ".join(dict.fromkeys(r["author"] for r in res))
            if "see credits" in str(e.get("author", "")) or not e.get("author"):
                e["author"] = authors
                changed = True
        if changed:
            json.dump(man, open(man_path, "w"), indent=1, ensure_ascii=False)

    lines = [
        "# R6-pbr credits — PBR materials, foliage cards, HDRIs",
        "",
        "All files below were produced by agent R6-pbr from the listed sources (scripts: `scripts/research/R6/`).",
        "Processing: resizing, cropping, packing roughness/metalness/AO into ORM, colour/exposure correction, seamless",
        "cross-fade or mirror tiling, cut-outs (alpha mattes) and normal maps derived from the photos/scans.",
        "Files derived from **CC BY-SA** photos are themselves distributed under the same CC BY-SA licence;",
        "**CC BY** photos require the attribution below. CC0 / Public-Domain-Mark sources need no attribution (credited anyway).",
        "",
        "Licence links: " + ", ".join(f"[{k}]({v})" for k, v in LIC_URL.items()),
        "",
        "| shipped path | source URL | author | licence |",
        "|---|---|---|---|",
    ]
    for name, key, shipped, r in rows:
        lines.append(f"| `{shipped}` | {r['url']} ({r['what']}) | {r['author']} | {r['license']} |")
    lines += ["", f"Total rows: {len(rows)}."]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("rows", len(rows), "->", OUT)
    for k, u in unresolved:
        print("UNRESOLVED", k, u)


if __name__ == "__main__":
    main()
