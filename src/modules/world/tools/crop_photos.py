#!/usr/bin/env python3
"""Crop real photos (Openverse/Flickr/Commons CC downloads) into sign / interior / produce / facade
textures for the world module + write public/assets/gen/world/signs.json and credits.
usage: crop_photos.py CROPS.json META1.jsonl [META2.jsonl ...]
CROPS.json: [{"src": "/abs/path.jpg", "box": [x0,y0,x1,y1] (fractions), "id": "name", "cat": "gold,shop", "glow": 0, "max": 768}]"""
import json, os, sys
from PIL import Image, ImageEnhance
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../../..'))
OUT = os.path.join(ROOT, 'public/assets/gen/world/signs')
os.makedirs(OUT, exist_ok=True)
crops = json.load(open(sys.argv[1]))
meta = {}
for mp in sys.argv[2:]:
    for l in open(mp, encoding='utf-8'):
        try:
            d = json.loads(l); meta[os.path.basename(d['file'])[:8]] = d
        except Exception: pass
items, credits = [], []
for c in crops:
    im = Image.open(c['src']).convert('RGB')
    W, H = im.size
    x0, y0, x1, y1 = c['box']
    im = im.crop((int(x0 * W), int(y0 * H), int(x1 * W), int(y1 * H)))
    mx = c.get('max', 768)
    s = min(1.0, mx / max(im.size))
    if s < 1: im = im.resize((max(8, int(im.size[0] * s)), max(8, int(im.size[1] * s))), Image.LANCZOS)
    if c.get('sat'): im = ImageEnhance.Color(im).enhance(c['sat'])
    fn = c['id'] + '.jpg'
    im.save(os.path.join(OUT, fn), quality=88)
    items.append({'id': c['id'], 'file': 'signs/' + fn, 'cat': c['cat'], 'glow': c.get('glow', 0), 'aspect': round(im.size[0] / im.size[1], 3), 'w': min(768, im.size[0]), 'h': min(768, im.size[1])})
    m = meta.get(os.path.basename(c['src'])[:8], {})
    credits.append(f"| gen/world/signs/{fn} | {m.get('title','')} | {m.get('creator','')} | {m.get('license','')} {m.get('license_version','')} | {m.get('landing','')} |")
json.dump({'items': items}, open(os.path.join(ROOT, 'public/assets/gen/world/signs.json'), 'w'), indent=1, ensure_ascii=False)
os.makedirs(os.path.join(ROOT, 'references/credits'), exist_ok=True)
with open(os.path.join(ROOT, 'references/credits/world.md'), 'w', encoding='utf-8') as f:
    f.write('# World module — third-party images (cropped from real photos)\n\n')
    f.write('Generated by src/modules/world/tools/crop_photos.py from Openverse (CC BY / CC BY-SA / CC0 / PDM) downloads.\n')
    f.write('Also uses the shared libraries credited by the research agents (textures/pbr, textures/world, textures/foliage, img/signs, hdri).\n\n')
    f.write('| file | title | author | licence | source |\n|---|---|---|---|---|\n')
    f.write('\n'.join(credits) + '\n')
print('cropped', len(items))
